//! Pure projection of retained collation records into sorted Rust table rows.
//!
//! This does not select or verify new locales, or observe a native collator.

use crate::{Result, rust_bytes};
use serde::Deserialize;
use std::collections::BTreeMap;
use std::fmt::Write;

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Row {
    pub name: String,
    pub tag: String,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Table {
    rows: Vec<Row>,
    variant: Option<i64>,
}

impl Table {
    /// Project truthy final string tags. Verification flags and metadata do not
    /// override the final tag. Null and empty tags are omitted.
    pub fn from_verification(json: &[u8]) -> Result<Self> {
        #[derive(Deserialize)]
        struct Verification {
            locales: BTreeMap<String, Entry>,
        }
        #[derive(Deserialize)]
        struct Entry {
            tag: Tag,
        }
        #[derive(Deserialize)]
        #[serde(untagged)]
        enum Tag {
            Text(String),
            Null,
        }
        let input: Verification = serde_json::from_slice(json)?;
        let rows = input
            .locales
            .into_iter()
            .filter_map(|(name, entry)| match entry.tag {
                Tag::Text(tag) if !tag.is_empty() => Some(Row { name, tag }),
                _ => None,
            })
            .collect();
        Ok(Self {
            rows,
            variant: None,
        })
    }

    /// Project one explicit measurement variant for every candidate. Negative
    /// indices count from each entry's end, as in the original list indexing.
    /// Empty string tags are retained here. An unavailable index is an error.
    pub fn from_candidates(json: &[u8], variant: i64) -> Result<Self> {
        #[derive(Deserialize)]
        struct Candidates {
            locales: BTreeMap<String, Entry>,
        }
        #[derive(Deserialize)]
        struct Entry {
            tags: Vec<String>,
        }
        let input: Candidates = serde_json::from_slice(json)?;
        let mut rows = Vec::new();
        for (name, entry) in input.locales {
            let index = if variant < 0 {
                usize::try_from(variant.unsigned_abs())
                    .ok()
                    .and_then(|distance| entry.tags.len().checked_sub(distance))
            } else {
                usize::try_from(variant).ok()
            };
            let tag = index
                .and_then(|index| entry.tags.get(index))
                .ok_or_else(|| {
                    format!("candidate variant {variant} is unavailable for locale {name:?}")
                })?
                .clone();
            rows.push(Row { name, tag });
        }
        Ok(Self {
            rows,
            variant: Some(variant),
        })
    }

    /// Rows retain raw names and tags, sorted by name without normalization.
    pub fn rows(&self) -> &[Row] {
        &self.rows
    }

    /// Emit source only. The caller owns output paths and any table update.
    pub fn rust_source(&self) -> String {
        let mut output = match self.variant {
            Some(variant) => format!("//! MEASUREMENT BUILD of candidate {variant}; do not commit.\n"),
            None => "//! Generated by fastmash-locale-tools from collation verification data; do not edit.\n".into(),
        };
        output.push_str(
            "/// Sorted by glibc name for binary search.\n\
pub(super) static COLLATION: &[(&[u8], &str)] = &[\n",
        );
        for (index, row) in self.rows.iter().enumerate() {
            if index != 0 {
                output.push('\n');
            }
            write!(
                output,
                "    ({}, {:?}),",
                rust_bytes(row.name.as_bytes()),
                row.tag
            )
            .expect("writing to a String cannot fail");
        }
        output.push_str("\n];\n");
        output
    }
}
